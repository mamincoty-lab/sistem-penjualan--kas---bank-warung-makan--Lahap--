create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  order_type text not null default 'takeaway' check (order_type in ('dine-in', 'takeaway', 'delivery')),
  table_number text,
  status text not null default 'paid' check (status in ('open', 'paid', 'void', 'refunded')),
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  discount_type text not null default 'none' check (discount_type in ('none', 'percent', 'amount')),
  discount_value numeric(12, 2) not null default 0 check (discount_value >= 0),
  tax_percent numeric(5, 2) not null default 0 check (tax_percent >= 0),
  service_percent numeric(5, 2) not null default 0 check (service_percent >= 0),
  total_amount numeric(12, 2) not null check (total_amount >= 0),
  cashier_name text not null default 'Kasir',
  created_at timestamptz not null default now()
);
alter table public.orders add column if not exists source text not null default 'walk_in';
alter table public.orders add column if not exists platform_fee numeric(12, 2) not null default 0;
