create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Makanan',
  price numeric(12, 2) not null check (price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null references public.menu_items(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  total_amount numeric(12, 2) generated always as (quantity * unit_price) stored,
  payment_method text not null default 'Cash' check (payment_method in ('Cash', 'Transfer', 'QRIS')),
  sale_date timestamptz not null default now(),
  voided_at timestamptz,
  voided_by text,
  void_reason text
);
alter table public.sales add column if not exists voided_at timestamptz;
alter table public.sales add column if not exists voided_by text;
alter table public.sales add column if not exists void_reason text;

create table if not exists public.cash_bank_transactions (
  id bigint generated by default as identity primary key,
  sale_id bigint references public.sales(id) on delete set null,
  transaction_type text not null check (transaction_type in ('Income', 'Expense')),
  account text not null default 'Kas' check (account in ('Kas', 'Bank')),
  category text not null default 'Lainnya',
  amount numeric(12, 2) not null check (amount > 0),
  note text,
  transaction_date timestamptz not null default now()
);

alter table public.cash_bank_transactions add column if not exists approval_status text not null default 'approved' check (approval_status in ('pending', 'approved', 'rejected'));
alter table public.cash_bank_transactions add column if not exists approved_by text;
alter table public.cash_bank_transactions add column if not exists receipt_path text;
alter table public.cash_bank_transactions add column if not exists voided_at timestamptz;
alter table public.cash_bank_transactions add column if not exists voided_by text;
alter table public.cash_bank_transactions add column if not exists void_reason text;
alter table public.cash_bank_transactions add column if not exists transaction_role text not null default 'operating';
alter table public.cash_bank_transactions add column if not exists reconciliation_status text not null default 'unmatched';

